#!/usr/bin/env python3
"""Build bounded phrase weights from pinned Leipzig news sentence samples."""

import argparse
from collections import Counter
import hashlib
import math
from pathlib import Path
import re
import tarfile

ROOT = Path(__file__).resolve().parents[1]
SOURCES = {
    "eng": ("eng_news_2020_10K", "c2936906d1e010dd68f0b2b95bf0ee50d72eeafdeaa78cc8ae84c60a7659ac15"),
    "heb": ("heb_news_2020_10K", "6dabd192ba5f3e30fa4d397944b4a73b0ff7dae2cdf63094f1d662e4e44bc6dd"),
}
TOKEN = re.compile(r"[a-zA-Z]+|[א-ת]+")


def phrase_counts(sentences):
    words, pairs = Counter(), Counter()
    for sentence in sentences:
        tokens = list(TOKEN.finditer(sentence))
        words.update(token.group().lower() for token in tokens)
        for left, right in zip(tokens, tokens[1:]):
            if sentence[left.end():right.start()].isspace():
                pairs[left.group().lower(), right.group().lower()] += 1
    return words, pairs


def weights(words, pairs, allowed):
    total = sum(words.values())
    selected = []
    for (previous, following), count in pairs.items():
        if count < 5 or previous not in allowed or following not in allowed:
            continue
        # Require both repeated evidence and a useful share of this predecessor.
        association = count * total / (words[previous] * words[following])
        if count / words[previous] < 0.05 or association < 3:
            continue
        weight = min(4.0, 1.0 + math.log2(association))
        selected.append((previous, following, weight, count, words[previous], words[following]))
    return sorted(sorted(selected, key=lambda row: (-row[3], row[:2]))[:512])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("english", type=Path)
    parser.add_argument("hebrew", type=Path)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    lines = ["# Measured phrase priors from Leipzig Corpora Collection, 10,000 news sentences per language.",
             "# Columns: previous, next, weight, pair count, previous count, next count.",
             "# Weight = min(4, 1 + log2(pair_count * token_total / (previous_count * next_count))).",
             "# Minimum count 5, conditional frequency 0.05, association 3; at most 512 pairs per language.",
             "# Generated by scripts/build_phrases.py; original sentences are not bundled."]
    for lang, archive in [("eng", args.english), ("heb", args.hebrew)]:
        name, checksum = SOURCES[lang]
        if hashlib.sha256(archive.read_bytes()).hexdigest() != checksum:
            parser.error(f"{archive}: checksum does not match pinned {name}")
        with tarfile.open(archive) as corpus:
            sentences = corpus.extractfile(f"{name}/{name}-sentences.txt").read().decode("utf-8")
        words, pairs = phrase_counts(row.split("\t", 1)[1] for row in sentences.splitlines())
        prefix = "en" if lang == "eng" else "he"
        dictionary = set((ROOT / f"{prefix}_dict.txt").read_text(encoding="utf-8").lower().splitlines())
        frequent = set((ROOT / f"{prefix}_freq.txt").read_text(encoding="utf-8").lower().splitlines()[:20_000])
        allowed = {word for word in dictionary & frequent if 2 <= len(word) <= 20}
        lines.extend([f"# Source: https://downloads.wortschatz-leipzig.de/corpora/{name}.tar.gz",
                      f"# SHA256: {checksum}; token total: {sum(words.values())}"])
        lines.extend("\t".join([previous, following, f"{weight:.3f}", str(count), str(left), str(right)])
                     for previous, following, weight, count, left, right in weights(words, pairs, allowed))
    output = "\n".join(lines) + "\n"
    path = ROOT / "src/phrase_counts.tsv"
    if args.check:
        return output != path.read_text(encoding="utf-8")
    path.write_text(output, encoding="utf-8")
    print(f"Wrote {sum(not line.startswith('#') for line in lines)} measured phrase priors")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
