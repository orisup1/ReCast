#!/usr/bin/env python3
"""Build local 1-to-4-gram counts from pinned Leipzig news sentence samples."""

import argparse
from collections import Counter
import hashlib
from pathlib import Path
import tarfile
import unicodedata

from build_phrases import ROOT, SOURCES, TOKEN

ORDER = 4
MIN_COUNT = 2
# Joined forms are excluded instead of treating their pieces as ordinary words.
JOINERS = frozenset("_'’‘ʼ-־‐‑׳״")


def _word_part(character):
    return (
        character.isalnum()
        or character in JOINERS
        or unicodedata.category(character).startswith("M")
    )


def _language(word):
    return "eng" if word[0].isascii() else "heb"


def sentence_runs(sentence):
    """Yield same-script words joined only by whitespace within one sentence.

    Ordinary punctuation separates runs. Digits, underscores, apostrophes,
    hyphens, and unsupported or mixed-script letters invalidate adjacent word
    fragments, so contractions and identifiers do not become training words.
    """
    run = []
    previous_end = 0
    for match in TOKEN.finditer(sentence):
        word = match.group().lower()
        valid = (
            len(word) <= 32
            and (match.start() == 0 or not _word_part(sentence[match.start() - 1]))
            and (match.end() == len(sentence) or not _word_part(sentence[match.end()]))
        )
        consecutive = (
            run
            and sentence[previous_end:match.start()].isspace()
            and _language(run[-1]) == _language(word)
        )
        if not valid or not consecutive:
            if run:
                yield tuple(run)
                run = []
        if valid:
            run.append(word)
        previous_end = match.end()
    if run:
        yield tuple(run)


def ngram_counts(sentences, language=None):
    """Count every 1-to-4-gram, including contexts at the end of a run."""
    counts = Counter()
    for sentence in sentences:
        for run in sentence_runs(sentence):
            if language is not None and _language(run[0]) != language:
                continue
            for start in range(len(run)):
                for size in range(1, min(ORDER, len(run) - start) + 1):
                    counts[run[start:start + size]] += 1
    return counts


def read_sentences(archive, language):
    """Verify a pinned archive and read only its expected regular-file member."""
    archive = Path(archive)
    name, checksum = SOURCES[language]
    digest = hashlib.sha256()
    with archive.open("rb") as source:
        for block in iter(lambda: source.read(1024 * 1024), b""):
            digest.update(block)
    if digest.hexdigest() != checksum:
        raise ValueError(f"{archive}: checksum does not match pinned {name}")
    with tarfile.open(archive) as corpus:
        member = corpus.getmember(f"{name}/{name}-sentences.txt")
        if not member.isfile():
            raise ValueError(f"{archive}: expected a regular sentence file")
        with corpus.extractfile(member) as source:
            text = source.read().decode("utf-8")
    sentences = []
    for line in text.splitlines():
        if not line:
            continue
        identifier, separator, sentence = line.partition("\t")
        if not separator or not identifier.isascii() or not identifier.isdecimal():
            raise ValueError(f"{archive}: invalid sentence row")
        sentences.append(sentence)
    return sentences


def render_counts(language_counts):
    """Render globally sorted measured counts and unpruned denominators."""
    lines = [
        "# Measured intent language model from Leipzig Corpora Collection, 10,000 news sentences per language.",
        "# Columns: n-gram (space-separated words), count, context_count.",
        "# Maximum order: 4; lowercase ASCII English or Hebrew letters; word length 1..32.",
        "# Runs require whitespace-only same-script adjacency; sentence and punctuation boundaries are never crossed.",
        "# Joined forms containing digits, underscores, apostrophes, hyphens, or mixed scripts are excluded.",
        "# Each corpus contributes its matching script only; all orders are measured before pruning.",
        "# Pruning: retain every n-gram with count >= 2; no row cap or invented counts.",
        "# Unigram context_count is the language token total; higher orders use the raw prefix count, including sentence-final contexts.",
        "# Generated by scripts/build_intent.py; only aggregates are bundled, never original sentences.",
    ]
    rows = []
    for language in ("eng", "heb"):
        counts = language_counts[language]
        total = sum(count for gram, count in counts.items() if len(gram) == 1)
        name, checksum = SOURCES[language]
        lines.extend([
            f"# Source: https://downloads.wortschatz-leipzig.de/corpora/{name}.tar.gz",
            f"# SHA256: {checksum}; language: {language}; token total: {total}",
        ])
        for gram, count in counts.items():
            if count >= MIN_COUNT:
                context_count = total if len(gram) == 1 else counts[gram[:-1]]
                rows.append((" ".join(gram), count, context_count))
    lines.extend(f"{key}\t{count}\t{context_count}" for key, count, context_count in sorted(rows))
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("english", type=Path)
    parser.add_argument("hebrew", type=Path)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--output", type=Path, default=ROOT / "src/intent_counts.tsv")
    args = parser.parse_args(argv)
    try:
        counts = {
            language: ngram_counts(read_sentences(archive, language), language)
            for language, archive in (("eng", args.english), ("heb", args.hebrew))
        }
        output = render_counts(counts)
        if args.check:
            if not args.output.exists() or args.output.read_text(encoding="utf-8") != output:
                print(f"{args.output}: generated counts differ")
                return 1
            return 0
        args.output.write_text(output, encoding="utf-8")
    except (OSError, ValueError, KeyError, tarfile.TarError) as error:
        parser.error(str(error))
    row_count = sum(not line.startswith("#") for line in output.splitlines())
    print(f"Wrote {row_count} measured intent n-grams to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
